package com.example.data.words

import com.example.domain.CategoryId
import com.example.domain.DifficultyLevel
import com.example.domain.WordEntry

internal fun buildCategoryWords(
    prefix: String,
    category: CategoryId,
    hintEn: String,
    hintHi: String,
    crewEn: List<String>,
    crewHi: List<String>,
    bluffEn: List<String>,
    bluffHi: List<String>,
    pairs: List<Pair<String, String>>
): List<WordEntry> = pairs.mapIndexed { idx, (en, hi) ->
    val diff = when {
        idx < 35 -> DifficultyLevel.EASY
        idx < 70 -> DifficultyLevel.MEDIUM
        else -> DifficultyLevel.HARD
    }
    WordEntry(
        id = "${prefix}_${idx + 1}",
        category = category,
        difficulty = diff,
        wordEn = en,
        wordHi = hi,
        hintEn = hintEn,
        hintHi = hintHi,
        crewCluesEn = crewEn,
        crewCluesHi = crewHi,
        bluffCluesEn = bluffEn,
        bluffCluesHi = bluffHi
    )
}

